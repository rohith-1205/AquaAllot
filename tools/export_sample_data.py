"""
export_sample_data.py - writes frontend/src/services/mockData.js from backend/demo_data.py.

The dashboard shows this sample data only while the backend is not running.
Run it again after changing demo_data.py so both stay identical:

    python tools/export_sample_data.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))

import demo_data  # noqa: E402
import services  # noqa: E402
from store import Store  # noqa: E402


def main():
    store = Store(mongo_uri=None)
    store.replace_all("users", demo_data.make_users())
    store.replace_all("stations", demo_data.make_stations())
    store.replace_all("transactions", demo_data.make_transactions())
    store.replace_all("settings", demo_data.make_settings())

    exports = {
        "initialUsers": store.all("users"),
        "initialStations": store.all("stations"),
        "initialTransactions": store.all("transactions", limit=60),
        "initialAlerts": demo_data.make_alerts(),
        "initialAnomalies": demo_data.make_anomalies(),
        "initialAnalytics": services.analytics(store),
    }

    lines = [
        "// Sample data shown ONLY while the backend is not running.",
        "// Generated by tools/export_sample_data.py from backend/demo_data.py – do not edit by hand.",
        "",
    ]
    for name, value in exports.items():
        lines.append(f"export const {name} = {json.dumps(value, indent=2, ensure_ascii=False)};")
        lines.append("")

    target = os.path.join(ROOT, "frontend", "src", "services", "mockData.js")
    with open(target, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))
    print(f"✓ wrote {target}")


if __name__ == "__main__":
    main()
